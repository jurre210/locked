export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;   // 5 wide plus one column of tracking

const cache = new Map();

function glyph(ch, colour){
  const key = ch + colour;
  let s = cache.get(key);
  if (s) return s;
  const rows = G[ch] || G[ch.toUpperCase()] || G['?'];
  s = bake(rows, { '#': colour });
  cache.set(key, s);
  return s;
}

/** Width of a string in virtual pixels at the given scale. */
export function textWidth(str, scale = 1){
  return Math.max(0, String(str).length * ADVANCE - 1) * scale;
}

/**
 * Draw crisp pixel text.
 * @param {object} o { colour, scale, align: 'left'|'centre'|'right', shadow, alpha }
 */
export function drawText(ctx, str, x, y, o = {}){
  const { colour = '#ffffff', scale = 1, align = 'left', shadow = null, alpha = 1 } = o;
  const text = String(str).toUpperCase();
  const w = textWidth(text, scale);
  let px = align === 'centre' ? Math.round(x - w / 2) : align === 'right' ? Math.round(x - w) : Math.round(x);
  const py = Math.round(y);

  ctx.save();
  if (alpha !== 1) ctx.globalAlpha = alpha;
  const run = (col, ox, oy) => {
    let cx = px + ox;
    for (const ch of text){
      if (ch !== ' '){
        const s = glyph(ch, col);
        ctx.drawImage(s.c, cx, py + oy, GLYPH_W * scale, GLYPH_H * scale);
      }
      cx += ADVANCE * scale;
    }
  };
  if (shadow) run(shadow, scale, scale);
  run(colour, 0, 0);
  ctx.restore();
  return w;
}

/** Word-wrap into lines that fit `maxW` virtual pixels. */
export function wrap(str, maxW, scale = 1){
  const words = String(str).split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words){
    const test = line ? line + ' ' + word : word;
    if (textWidth(test, scale) > maxW && line){ lines.push(line); line = word; }
    else line = test;
  }
  if (line) lines.push(line);
  return lines;
}
